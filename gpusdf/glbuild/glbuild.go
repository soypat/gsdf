// AppendGenericSliceDecl appends a mutable function scope array declaration. Arrays declared with var
// can be indexed dynamically in WGSL. appendElement must append a WGSL expression of type typename.
//
//	var <varname> = array<typename,nelem>(...);
func AppendGenericSliceDecl(b []byte, typename, varname string, nelem int, appendElement func(b []byte, i int) []byte) []byte {
	lineStart := len(b)
	b = appendStartSliceDecl(b, typename, varname, nelem)
	for i := 0; i < nelem; i++ {
		last := i == nelem-1
		b = appendElement(b, i)
		if !last {
			b = append(b, ',')
			lineLen := len(b) - lineStart
			if lineLen > maxLineLim {
				b = append(b, '\n') // Break up line for VERY long polygon vertex lists.
				lineStart = len(b)
			}
		}
	}
	b = append(b, ");\n"...)
	return b
}

