var visualizerEntry []byte

// WriteRaymarchSDF3 writes the SDF function declarations of obj followed by a
// `fn sdf(p: vec3f) -> f32` function that evaluates obj and a raymarching library
// that renders the SDF. The library exposes the following functions:
//
//	// gsdfRender returns the color of a pixel at fragCoord (origin at bottom-left of image).
//	fn gsdfRender(fragCoord: vec2f, resolution: vec2f, yaw: f32, pitch: f32, camDist: f32, tmax: f32, aa: i32) -> vec3f
//	// gsdfCalcNormal calculates the normal of the SDF at pos.
//	fn gsdfCalcNormal(pos: vec3f, eps: f32) -> vec3f
//
// No entry points are written; the caller must write the vertex/fragment or compute entry points.
func (p *Programmer) WriteRaymarchSDF3(w io.Writer, obj Shader3D) (n int, objs []ShaderObject, err error) {
	baseName, n, objs, err := p.WriteSDFDecl(w, obj)
	if err != nil {
		return n, objs, err
	}
	ngot, err := fmt.Fprintf(w, "\nfn sdf(p: vec3f) -> f32 { return %s(p); }\n\n", baseName)
	n += ngot
	if err != nil {
		return n, objs, err
	}
	ngot, err = w.Write(raymarchLib)
	n += ngot
	return n, objs, err
}

// WriteVisualizerSDF3 generates a standalone WGSL program that renders the SDF in
// compute shader based visualizers such as https://compute.toys. The camera orbits the origin and is controlled with the mouse.
// Shapes should be scaled and translated to fit in a sphere of radius ~1 centered at the origin.
func (p *Programmer) WriteVisualizerSDF3(w io.Writer, obj Shader3D) (n int, objs []ShaderObject, err error) {
	n, objs, err = p.WriteRaymarchSDF3(w, obj)
	if err != nil {
		return n, objs, err
	}
	for i := range objs {
		if objs[i].IsBindable() {
			return n, objs, errors.New("visualization shader does not support binding shader buffers. Create your SDFs with no shader buffers by setting FlagNoShaderBuffers in gsdf.Builder flags")
		}
	}
	ngot, err := w.Write(visualizerEntry)
	n += ngot
	return n, objs, err
}

// WriteSDFDecl writes the SDF shader function declarations and returns the top-level SDF function name.
// Shader object buffer declarations (pooled by element type) and their accessor functions are also written.
func (p *Programmer) WriteSDFDecl(w io.Writer, s Shader) (baseName string, n int, objs []ShaderObject, err error) {
	baseName, nodes, err := ParseAppendNodes(p.scratchNodes[:0], s)
	if err != nil {
		return "", 0, nil, err
	}
	n, objs, err = p.writeShaders(w, nodes)
	if err != nil {
		return "", n, objs, err
	}
	return baseName, n, objs, nil
}

func (p *Programmer) writeShaders(w io.Writer, nodes []Shader) (n int, objs []ShaderObject, err error) {
	clear(p.names)
	p.scratch = p.scratch[:0]
	p.objsScratch = p.objsScratch[:0]
	p.pools = p.pools[:0]
	// First pass: gather all Shader Objects and discard duplicates.
	for i := len(nodes) - 1; i >= 0; i-- {
		node := nodes[i]
		start := len(p.objsScratch)
		p.objsScratch = node.AppendShaderObjects(p.objsScratch)
		kept := start
	OBJWRITE:
		for j := start; j < len(p.objsScratch); j++ {
			obj := p.objsScratch[j]
			if obj.Binding != -1 {
				return n, nil, fmt.Errorf("shader buffer object binding should be set to -1 until shader generated for %T, %q", unwraproot(node), obj.NamePtr)
			} else if isWGSLReserved(obj.NamePtr) {
				return n, nil, fmt.Errorf("shader object name %q of %T is a WGSL reserved word", obj.NamePtr, unwraproot(node))
			}
			nameHash := hash(obj.NamePtr, 0)
			_, nameConflict := p.names[nameHash]
			if nameConflict {
				for _, old := range p.objsScratch[:kept] {
					if !bytes.Equal(old.NamePtr, obj.NamePtr) {
						continue
					}
					if obj.IsFunction() && old.IsFunction() && bytes.Equal(obj.funcSource, old.funcSource) {
						continue OBJWRITE // Skip this function, is duplicate.
					} else if obj.IsBindable() && old.IsBindable() && obj.Data == old.Data && obj.Size == old.Size && obj.Element == old.Element {
						continue OBJWRITE // Skip this object, is duplicate and already has been added.
					}
					break // Conflict is not identical.
				}
				return n, nil, fmt.Errorf("shader object name conflict resolution not implemented: %T has object with conflicting name %q", unwraproot(node), obj.NamePtr)
			}
			p.names[nameHash] = nameHash
			p.objsScratch[kept] = obj
			kept++
		}
		p.objsScratch = p.objsScratch[:kept]
	}

	// Second pass: pool buffers by element type and assign binding points and offsets.
	for i := range p.objsScratch {
		obj := &p.objsScratch[i]
		if !obj.IsBindable() {
			continue
		}
		typename, err := wgslTypename(obj.Element)
		if err != nil {
			return n, nil, fmt.Errorf("shader object %q: %w", obj.NamePtr, err)
		}
		poolIdx := -1
		for k := range p.pools {
			if p.pools[k].typename == typename {
				poolIdx = k
				break
			}
		}
		if poolIdx < 0 {
			poolIdx = len(p.pools)
			p.pools = append(p.pools, objPool{typename: typename})
		}
		obj.Binding = poolIdx
		obj.Offset = p.pools[poolIdx].nelem
		p.pools[poolIdx].nelem += obj.NumElements()
		err = obj.Validate()
		if err != nil {
			return n, nil, fmt.Errorf("shader object %q: %w", obj.NamePtr, err)
		}
	}

	// Write pooled buffer declarations, accessors and functions.
	for i := range p.pools {
		p.scratch = appendPoolDecl(p.scratch, i, p.pools[i].typename)
	}
	for i := range p.objsScratch {
		obj := &p.objsScratch[i]
		if obj.IsFunction() {
			p.scratch = append(p.scratch, '\n')
			p.scratch = append(p.scratch, obj.funcSource...)
			p.scratch = append(p.scratch, '\n')
			continue
		}
		p.scratch = appendObjectAccessors(p.scratch, *obj, p.pools[obj.Binding].typename)
	}
	if len(p.scratch) > 0 {
		ngot, err := w.Write(p.scratch)
		n += ngot
		if err != nil {
			return n, nil, err
		}
	}

	for i := len(nodes) - 1; i >= 0; i-- {
		node := nodes[i]
		var name, body []byte
		p.scratch, name, body = AppendShaderSource(p.scratch[:0], node)
		if isWGSLReserved(name) {
			return n, nil, fmt.Errorf("shader name %q of %T is a WGSL reserved word", name, unwraproot(node))
		}
		nameHash := hash(name, 0)
		bodyHash := hash(body, nameHash) // Body hash mixes name as well.
		gotBodyHash, nameConflict := p.names[nameHash]
		if nameConflict {
			// Name already exists in tree, check if bodies are identical.
			if bodyHash == gotBodyHash {
				continue // Shader already written and is identical, skip.
			}
			// Look for identical shader
			var conflictBody []byte
			for j := i + 1; j < len(nodes); j++ {
				conflictBody = nodes[j].AppendShaderName(conflictBody[:0])
				if bytes.Equal(conflictBody, name) {
					conflictBody = nodes[j].AppendWGSLBody(conflictBody[:0])
					break
				}
				conflictBody = conflictBody[:0]
			}
			return n, nil, fmt.Errorf("duplicate %T shader name %q w/ body:\n%s\n\nconflict with distinct shader with same name:\n%s", unwraproot(node), name, body, conflictBody)
		} else {
			p.names[nameHash] = bodyHash // Not found, add it.
		}
		ngot, err := w.Write(p.scratch)
		n += ngot
		if err != nil {
			return n, nil, err
		}
	}
	objs = append(objs[:0], p.objsScratch...) // Clone slice and return it.
	return n, objs, err
}

func appendPoolName(dst []byte, typename string) []byte {
	dst = append(dst, "gsdfPool_"...)
	return append(dst, typename...)
}

// appendPoolDecl appends the pooled storage buffer declaration:
//
//	@group(1) @binding(<binding>) var<storage, read> gsdfPool_<typename>: array<typename>;
func appendPoolDecl(dst []byte, binding int, typename string) []byte {
	dst = append(dst, "@group("...)
	dst = strconv.AppendInt(dst, ObjectsBindGroup, 10)
	dst = append(dst, ") @binding("...)
	dst = strconv.AppendInt(dst, int64(binding), 10)
	dst = append(dst, ") var<storage, read> "...)
	dst = appendPoolName(dst, typename)
	dst = append(dst, ": array<"...)
	dst = append(dst, typename...)
	dst = append(dst, ">;\n"...)
	return dst
}

// appendObjectAccessors appends the accessor functions of a buffer object:
//
//	fn <name>_at(i: i32) -> <typename> { return gsdfPool_<typename>[<offset>+i]; }
//	fn <name>_len() -> i32 { return <numElements>; }
func appendObjectAccessors(dst []byte, obj ShaderObject, typename string) []byte {
	dst = append(dst, "fn "...)
	dst = append(dst, obj.NamePtr...)
	dst = append(dst, "_at(i: i32) -> "...)
	dst = append(dst, typename...)
	dst = append(dst, " { return "...)
	dst = appendPoolName(dst, typename)
	dst = append(dst, '[')
	dst = strconv.AppendInt(dst, int64(obj.Offset), 10)
	dst = append(dst, "+i]; }\nfn "...)
	dst = append(dst, obj.NamePtr...)
	dst = append(dst, "_len() -> i32 { return "...)
	dst = strconv.AppendInt(dst, int64(obj.NumElements()), 10)
	dst = append(dst, "; }\n"...)
	return dst
}

const shorteningBufsize = 1024

func ShortenNames3D(root *Shader3D, maxRewriteLen int) error {
	scratch := make([]byte, shorteningBufsize)
	rewrite3 := func(a any, s3 *Shader3D) error {
		scratch = rewriteName3(s3, scratch, maxRewriteLen)
		return nil
	}
	rewrite2 := func(a any, s2 *Shader2D) error {
		scratch = rewriteName2(s2, scratch, maxRewriteLen)
		return nil
	}
	err := forEachNodeBFS(*root, rewrite3, rewrite2)
	if err != nil {
		return err
	}
	return rewrite3(nil, root)
}

func ShortenNames2D(root *Shader2D, maxRewriteLen int) error {
	scratch := make([]byte, shorteningBufsize)
	rewrite3 := func(a any, s3 *Shader3D) error {
		scratch = rewriteName3(s3, scratch, maxRewriteLen)
		return nil
	}
	rewrite2 := func(a any, s2 *Shader2D) error {
		scratch = rewriteName2(s2, scratch, maxRewriteLen)
		return nil
	}
	err := forEachNodeBFS(*root, rewrite3, rewrite2)
	if err != nil {
		return err
	}
	return rewrite2(nil, root)
}

func rewriteName3(s3 *Shader3D, scratch []byte, rewritelen int) []byte {
	sd3 := *s3
	if _, ok := sd3.(*nameOverloadShader3D); ok {
		return scratch // Already overloaded.
	}
	name, scratch := makeShortname(sd3, scratch, rewritelen)
	if name == nil {
		return scratch
	}
	*s3 = &nameOverloadShader3D{Shader: sd3, name: name}
	return scratch
}

func rewriteName2(s2 *Shader2D, scratch []byte, rewritelen int) []byte {
	sd2 := *s2
	if _, ok := sd2.(*nameOverloadShader2D); ok {
		return scratch // Already overloaded.
	}
	name, scratch := makeShortname(sd2, scratch, rewritelen)
	if name == nil {
		return scratch
	}
	*s2 = &nameOverloadShader2D{Shader: sd2, name: name}
	return scratch
}

// makeNewName creates.
func makeShortname(s Shader, scratch []byte, rewritelen int) (newNameOrNil []byte, newScratch []byte) {
	var h uint64 = 0xff51afd7ed558ccd
	scratch = s.AppendShaderName(scratch[:0])
	if len(scratch) < rewritelen {
		return nil, scratch // Already short name, no need to rewrite.
	}
	newName := append([]byte{}, scratch[:rewritelen]...)
	h = hash(scratch, h)
	scratch = s.AppendWGSLBody(scratch[:0])
	h = hash(scratch, h)
	newName = strconv.AppendUint(newName, h, 32)
	return newName, scratch
}

// ParseAppendNodes parses the shader object tree and appends all nodes in Depth First order
// to the dst Shader argument buffer and returns the result.
func ParseAppendNodes(dst []Shader, root Shader) (baseName string, nodes []Shader, err error) {
	if root == nil {
		return "", nil, errors.New("nil shader object")
	}
	baseName = string(root.AppendShaderName([]byte{}))
	if baseName == "" {
		return "", nil, errors.New("empty shader name")
	}
	dst, err = AppendAllNodes(dst, root)
	if err != nil {
		return "", nil, err
	}
	return baseName, dst, nil
}

// WriteShaders iterates over the argument nodes in reverse order and
// writes their WGSL code to the writer. scratch is an auxiliary buffer to avoid heap allocations.
//
// WriteShaders does not check for repeated shader names.
func WriteShaders(w io.Writer, nodes []Shader, scratch []byte) (n int, newscratch []byte, err error) {
	if scratch == nil {
		scratch = make([]byte, 1024)
	}
	var ngot int
	for i := len(nodes) - 1; i >= 0; i-- {
		ngot, scratch, err = WriteShader(w, nodes[i], scratch[:0])
		n += ngot
		if err != nil {
			return n, scratch, err
		}
	}
	return n, scratch, nil
}

// WriteShader writes the WGSL function of a single shader to w. See [AppendShaderSource].
func WriteShader(w io.Writer, s Shader, scratch []byte) (int, []byte, error) {
	scratch, _, _ = AppendShaderSource(scratch[:0], s)
	n, err := w.Write(scratch)
	return n, scratch, err
}

func (obj ShaderObject) Validate() error {
	if len(obj.NamePtr) == 0 {
		return errors.New("shader object zero-length name")
	} else if len(obj.funcSource) > 0 {
		return nil // Functions only have one required field besides NamePtr
	}
	if obj.Data == nil {
		return errors.New("shader object nil data pointer")
	} else if obj.Size == 0 {
		return errors.New("shader object zero/negative length data")
	} else if obj.Size < 0 {
		return errors.New("shader object negative length of data")
	} else if !obj.read {
		return errors.New("shader object no usage defined")
	} else if obj.Binding < 0 {
		return errors.New("shader object negative binding point")
	} else if obj.Offset < 0 {
		return errors.New("shader object negative offset")
	}
	_, err := wgslTypename(obj.Element)
	if err != nil {
		return err
	}
	return nil
}

// wgslTypename returns the WGSL type name of a storage buffer array element with the same memory layout as the Go type.
func wgslTypename(tp reflect.Type) (typename string, err error) {
	var stride uintptr // WGSL array stride of element.
	switch tp {
	case reflect.TypeOf(float32(0)):
		typename, stride = "f32", 4
	case reflect.TypeOf(uint32(0)):
		typename, stride = "u32", 4
	case reflect.TypeOf(int32(0)):
		typename, stride = "i32", 4
	case reflect.TypeOf(ms2.Vec{}), reflect.TypeOf([2]float32{}):
		typename, stride = "vec2f", 8
	case reflect.TypeOf([2]uint32{}):
		typename, stride = "vec2u", 8
	case reflect.TypeOf([2]int32{}):
		typename, stride = "vec2i", 8
	case reflect.TypeOf(ms3.Vec{}):
		typename, stride = "vec3f", 16 // ms3.Vec contains padding to align to 16 bytes.
	case reflect.TypeOf([2]ms2.Vec{}), reflect.TypeOf(ms3.Quat{}), reflect.TypeOf([4]float32{}):
		typename, stride = "vec4f", 16
	case reflect.TypeOf([4]uint32{}):
		typename, stride = "vec4u", 16
	case reflect.TypeOf([4]int32{}):
		typename, stride = "vec4i", 16
	case nil:
		return "", errors.New("nil element type")
	default:
		return "", fmt.Errorf("equivalent WGSL type not implemented for %s", tp.String())
	}
	if tp.Size() != stride {
		return "", fmt.Errorf("%s size %d does not match WGSL %s array stride %d", tp.String(), tp.Size(), typename, stride)
	}
	return typename, nil
}

// AppendShaderSource appends the WGSL code of a single shader to the dst byte buffer.  If dst's
// capacity is grown during the writing the buffer with augmented capacity is returned. If not the same input dst is returned.
// name and body byte slices pointing to the result buffer are also returned for convenience.
func AppendShaderSource(dst []byte, s Shader) (result, name, body []byte) {
	dst = append(dst, "fn "...)
	nameStart := len(dst)
	dst = s.AppendShaderName(dst)
	nameEnd := len(dst)
	_, is3D := s.(Shader3D)
	if is3D {
		dst = append(dst, "(p_in: vec3f) -> f32 {\nvar p = p_in;\n"...)
	} else {
		dst = append(dst, "(p_in: vec2f) -> f32 {\nvar p = p_in;\n"...)
	}
	bodyStart := len(dst)
	dst = s.AppendWGSLBody(dst)
	bodyEnd := len(dst)
	dst = append(dst, "\n}\n"...)
	return dst, dst[nameStart:nameEnd], dst[bodyStart:bodyEnd]
}

// isWGSLReserved returns true if name is a WGSL keyword or reserved word and thus not a valid identifier.
func isWGSLReserved(name []byte) bool {
	if len(name) == 1 && name[0] == '_' || len(name) >= 2 && name[0] == '_' && name[1] == '_' {
		return true // Identifiers can't be single underscore nor start with double underscore.
	}
	_, reserved := wgslReserved[string(name)]
	return reserved
}

