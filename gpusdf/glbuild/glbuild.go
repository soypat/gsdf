func appendMatDecl(b []byte, typename, name string, row, col int, arr []float32) []byte {
	b = append(b, "var "...)
	b = append(b, name...)
	b = append(b, '=')
	b = append(b, typename...)
	b = append(b, '(')
	for i := 0; i < row; i++ {
		for j := 0; j < col; j++ {
			v := arr[j*row+i] // Column major access, as per WGSL standard.
			b = AppendFloat(b, '-', '.', v)
			last := i == row-1 && j == col-1
			if !last {
				b = append(b, ',')
			}
		}
	}
	b = append(b, ");\n"...)
	return b
}

const decimalDigits = 9

// AppendFloat appends a float literal. A float literal always contains a decimal separator so it is
// interpreted as a floating point literal in WGSL, i.e: 1.0 is appended as "1.". neg and decimal
// can be used to substitute the minus sign and decimal point bytes, useful for generating identifiers.
func AppendFloat(b []byte, neg, decimal byte, v float32) []byte {
	start := len(b)
	b = strconv.AppendFloat(b, float64(v), 'f', decimalDigits, 32)
	idx := bytes.IndexByte(b[start:], '.')
	if decimal != '.' && idx >= 0 {
		b[start+idx] = decimal
	}
	if b[start] == '-' {
		b[start] = neg
	}
	// Finally trim zeroes.
	end := len(b)
	for i := len(b) - 1; idx >= 0 && i > idx+start && b[i] == '0'; i-- {
		end--
	}
	// TODO(soypat): Round off when find N consecutive 9's?
	return b[:end]
}

func AppendFloats(b []byte, sep, neg, decimal byte, s ...float32) []byte {
	for i, v := range s {
		b = AppendFloat(b, neg, decimal, v)
		if sep != 0 && i != len(s)-1 {
			b = append(b, sep)
		}
	}
	return b
}

