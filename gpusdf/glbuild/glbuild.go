// Shader stores information for automatically generating SDF Shader pipelines
// and evaluating them correctly on a GPU. Shaders generate WGSL (WebGPU Shading Language) code.
//
// The generated function signature for a [Shader3D] is:
//
//	fn <AppendShaderName>(p_in: vec3f) -> f32 {
//		var p = p_in;
//		<AppendWGSLBody>
//	}
//
// [Shader2D] functions are identical but receive a vec2f argument. The p variable is mutable inside the body.
type Shader interface {
	// AppendShaderName appends the name of the WGSL shader function
	// to the buffer and returns the result. It should be unique to that shader.
	AppendShaderName(b []byte) []byte
	// AppendWGSLBody appends the WGSL body of the shader function to the
	// buffer and returns the result.
	AppendWGSLBody(b []byte) []byte
	// AppendShaderObject appends "objects" (read as data) needed to
	// evaluate the shader correctly. See [ShaderObject] for more information
	// on what an object can represent.
	AppendShaderObjects(objs []ShaderObject) []ShaderObject
}

// ShaderObject is a handle to data needed to evaluate a [Shader] correctly.
// A ShaderObject could represent any of the following:
//   - Read-only storage buffer. Is a 1D array of structured data. Created with [MakeShaderBufferReadOnly].
//     Shader bodies access buffer elements exclusively through generated accessor functions, see [AppendObjectAt] and [AppendObjectLen].
//   - WGSL function. Created with [MakeShaderFunction].
type ShaderObject struct {
	// NamePtr is a pointer to the name of the buffer inside of the [Shader].
	// This lets the programmer edit the name if a naming conflict is found before generating the shader bodies.
	NamePtr []byte

	// Element is the element type of the buffer.
	Element reflect.Type
	// Data points to the start of buffer data.
	Data unsafe.Pointer
	// Size of buffer in bytes.
	Size int
	// Binding specifies the resource's binding point inside of bind group [ObjectsBindGroup] during shader execution.
	// Buffers of the same element type are pooled into a single binding.
	// Binding should be equal to -1 until the final binding point is allocated in shader generation.
	Binding int
	// Offset is the offset in number of elements of the buffer data inside the pooled binding.
	// Is set during shader generation.
	Offset int
	read   bool
	// for function shaders.
	funcSource []byte
}

// ObjectsBindGroup is the WGSL bind group index at which all [ShaderObject] storage buffers are bound.
const ObjectsBindGroup = 1

// ComputeEntryPoint is the name of the compute shader entry point generated by [Programmer.WriteComputeSDF3] and [Programmer.WriteComputeSDF2].
const ComputeEntryPoint = "main"

// Shader3D can create SDF shader source code for an arbitrary 3D shape.
type Shader3D interface {
	Shader
	// ForEachChild iterats over the Shader3D's direct Shader3D children.
	// Unary operations have one child i.e: Translate, Transform, Scale.
	// Binary operations have two children i.e: Union, Intersection, Difference.
	ForEachChild(userData any, fn func(userData any, s *Shader3D) error) error
	// Bounds returns the Shader3D's bounding box where the SDF is negative.
	Bounds() ms3.Box
}

// Shader2D can create SDF shader source code for an arbitrary 2D shape.
type Shader2D interface {
	Shader
	// ForEachChild iterats over the Shader2D's direct Shader2D children.
	// Unary operations have one child i.e: Translate, Scale.
	// Binary operations have two children i.e: Union, Intersection, Difference.
	ForEach2DChild(userData any, fn func(userData any, s *Shader2D) error) error
	// Bounds returns the Shader2D's bounding box where the SDF is negative.
	Bounds() ms2.Box
}

// shader3D2D can create SDF shader source code for a operation that receives 2D
// shaders to generate a 3D shape.
type shader3D2D interface {
	Shader3D
	ForEach2DChild(userData any, fn func(userData any, s *Shader2D) error) error
}

// Programmer implements shader generation logic for Shader type.
type Programmer struct {
	scratchNodes []Shader
	scratch      []byte
	objsScratch  []ShaderObject
	pools        []objPool
	// names maps shader names to body hashes for checking duplicates.
	names map[uint64]uint64
	// Invocations size in X (local group size) to give each compute work group.
	invocX int
}

// objPool is a group of buffer objects of the same element type that share a binding.
type objPool struct {
	typename string
	nelem    int
}

// MakeShaderFunction creates a [ShaderObject] that represents a WGSL function. shaderDef must start with
// the "fn" keyword followed by the function name, i.e:
//
//	fn gsdfRect2D(p: vec2f, x: f32, y: f32) -> f32 {
func MakeShaderFunction(shaderDef []byte) (sf ShaderObject, err error) {
	shaderDef = bytes.TrimSpace(shaderDef)
	const fnPrefix = "fn "
	if !bytes.HasPrefix(shaderDef, []byte(fnPrefix)) {
		return ShaderObject{}, errors.New("WGSL function definition must start with \"fn \"")
	}
	fnNameEnd := bytes.IndexByte(shaderDef, '(')
	if fnNameEnd < 0 {
		return ShaderObject{}, errors.New("unable to parse function name")
	}
	name := bytes.TrimSpace(shaderDef[len(fnPrefix):fnNameEnd])
	if len(name) == 0 {
		return ShaderObject{}, errors.New("empty function name")
	}
	sf = ShaderObject{
		NamePtr:    name,
		funcSource: shaderDef,
		Binding:    -1,
	}
	return sf, nil
}

func (ssbo ShaderObject) IsFunction() bool { return len(ssbo.funcSource) > 0 }
func (ssbo ShaderObject) IsBindable() bool { return !ssbo.IsFunction() }

// MakeShaderBufferReadOnly creates a read-only storage buffer [ShaderObject] with the argument name.
// Shader bodies should access the data via the generated accessor functions, see [AppendObjectAt] and [AppendObjectLen].
func MakeShaderBufferReadOnly[T any](namePtr []byte, data []T) (ssbo ShaderObject, err error) {
	var z T
	if len(data) == 0 {
		return ShaderObject{}, errors.New("shader object zero length data")
	}
	ssbo = ShaderObject{
		NamePtr: namePtr,
		Element: reflect.TypeOf(z),
		Data:    unsafe.Pointer(&data[0]),
		Size:    int(unsafe.Sizeof(z)) * len(data),
		read:    true,
	}
	err = ssbo.Validate()
	if err != nil {
		return ShaderObject{}, err
	}
	// Until shader pipeline we do not know where our buffer will be binded.
	// Programmer expects -1 binding until then.
	ssbo.Binding = -1
	return ssbo, nil
}

// NumElements returns the number of elements in the buffer object. Returns 0 for function objects.
func (obj ShaderObject) NumElements() int {
	if obj.IsFunction() || obj.Element == nil || obj.Element.Size() == 0 {
		return 0
	}
	return obj.Size / int(obj.Element.Size())
}

// AppendObjectAt appends a call to the accessor of the element at index idxExpr of the buffer object of name objName.
// idxExpr must be a WGSL expression of type i32. The resulting expression's type is that of the buffer element.
//
//	<objName>_at(<idxExpr>)
func AppendObjectAt(dst []byte, objName []byte, idxExpr string) []byte {
	dst = append(dst, objName...)
	dst = append(dst, "_at("...)
	dst = append(dst, idxExpr...)
	dst = append(dst, ')')
	return dst
}

// AppendObjectLen appends a call to the accessor of the number of elements (i32) of the buffer object of name objName.
//
//	<objName>_len()
func AppendObjectLen(dst []byte, objName []byte) []byte {
	dst = append(dst, objName...)
	dst = append(dst, "_len()"...)
	return dst
}

// NewDefaultProgrammer returns a Programmer with reasonable default parameters for use with WebGPU.
func NewDefaultProgrammer() *Programmer {
	return &Programmer{
		scratchNodes: make([]Shader, 64),
		scratch:      make([]byte, 1024), // Max length of shader token is around 1024..1060 characters.
		names:        make(map[uint64]uint64),
		invocX:       64,
	}
}

// SetComputeInvocations sets the work group local-sizes. x*y*z must be less than maximum number of invocations.
func (p *Programmer) SetComputeInvocations(x, y, z int) {
	if y != 1 || z != 1 {
		panic("unsupported")
	} else if x < 1 {
		panic("zero or negative X invocation size")
	}
	p.invocX = x
}

// ComputeInvocations returns the worker group invocation size in x y and z.
func (p *Programmer) ComputeInvocations() (int, int, int) {
	return p.invocX, 1, 1
}

// WriteComputeSDF3 creates the bare bones I/O compute program for calculating SDF
// and writes it to the writer. The program has the following bindings in bind group 0:
//   - binding 0: read-only storage buffer of vec3f positions (16 byte stride, see [ms3.Vec]).
//   - binding 1: read-write storage buffer of f32 distances, output of the program.
//   - binding 2: uniform vec4u. x component contains number of positions to evaluate.
//
// [ShaderObject] buffers are bound at bind group [ObjectsBindGroup] at the binding indicated by the returned objects.
// The entry point is [ComputeEntryPoint]. Dispatches may be two dimensional to overcome the maximum number of workgroups per dimension.
func (p *Programmer) WriteComputeSDF3(w io.Writer, obj Shader3D) (int, []ShaderObject, error) {
	return p.writeCompute(w, obj, "vec3f")
}

// WriteComputeSDF2 creates the bare bones I/O compute program for calculating SDF
// and writes it to the writer. See [Programmer.WriteComputeSDF3] for program bindings. Positions are vec2f.
func (p *Programmer) WriteComputeSDF2(w io.Writer, obj Shader2D) (int, []ShaderObject, error) {
	return p.writeCompute(w, obj, "vec2f")
}

func (p *Programmer) writeCompute(w io.Writer, obj Shader, posType string) (int, []ShaderObject, error) {
	baseName, n, objs, err := p.WriteSDFDecl(w, obj)
	if err != nil {
		return n, nil, err
	}
	ngot, err := fmt.Fprintf(w, `
@group(0) @binding(0) var<storage, read> gsdfPos: array<%s>;
@group(0) @binding(1) var<storage, read_write> gsdfDist: array<f32>;
@group(0) @binding(2) var<uniform> gsdfParams: vec4u; // x: number of positions to evaluate.

@compute @workgroup_size(%d, 1, 1)
fn %s(@builtin(global_invocation_id) gid: vec3u, @builtin(num_workgroups) nwg: vec3u) {
	let idx = gid.x + gid.y*nwg.x*%du;
	if (idx >= gsdfParams.x) {
		return;
	}
	gsdfDist[idx] = %s(gsdfPos[idx]);
}
`, posType, p.invocX, ComputeEntryPoint, p.invocX, baseName)
	n += ngot
	return n, objs, err
}

